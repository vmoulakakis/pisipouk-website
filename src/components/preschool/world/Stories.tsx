export function StoryBook({
  age,
  onComplete,
}: {
  age: Age;
  onComplete: () => void;
}) {
  const [book, setBook] = useState(0),
    [page, setPage] = useState(0),
    [choice, setChoice] = useState<number | null>(null),
    [status, setStatus] = useState(""),
    [busy, setBusy] = useState(false);
  const b = STORIES[book],
    imgs = [story, exterior, arrival, classroom];
  const text =
    page < 4
      ? b.pages[page]
      : choice === null
        ? "Διάλεξε πώς θα συνεχιστεί η ιστορία."
        : b.endings[choice];
  const agePrompt = [
    "Δείξε τον Πισιπούκ στην εικόνα.",
    "Πες ποιος είναι ο ήρωας και τι κάνει.",
    "Πώς νιώθει ο ήρωας; Τι θα του έλεγες;",
    "Πες την ιστορία με αρχή, μέση και δικό σου τέλος.",
  ][age];
  useEffect(() => {
    speechSynthesis?.getVoices();
    return () => speechSynthesis?.cancel();
  }, []);
  return (
    <section className="pw-story">
      <div className="pw-section-title">
        <small>ΤΟ ΔΕΝΤΡΟ ΤΩΝ ΙΣΤΟΡΙΩΝ</small>
        <h2>Κάθε ιστορία αρχίζει μαζί.</h2>
      </div>
      <p className="pw-game-hint"><strong>Πώς διαβάζουμε:</strong> 1. Διαλέγουμε ιστορία και κοιτάμε την εικόνα. 2. Ακούμε το παραμύθι. 3. Διαλέγουμε το τέλος. Μπορούμε να το αλλάξουμε όσες φορές θέλουμε.</p>
      <div className="pw-story-selector" role="group" aria-label="20 παραμύθια">
        {STORIES.map((item, i) => <button type="button" key={item.title} aria-pressed={i===book}
          onClick={() => {window.speechSynthesis?.cancel();setBook(i);setPage(0);setChoice(null);}}>
          <img loading="lazy" src={artworkDataUrl(PATTERNS[i % PATTERNS.length],age,true)} alt="" />
          <span>{item.title}</span>
        </button>)}
      </div>
      <article className="pw-book">
        <img
          src={book<3?imgs[page % 4]:artworkDataUrl(PATTERNS[book % PATTERNS.length],age,true)}
          alt={
            [
              "Ο Πισιπούκ και οι φίλοι του διαβάζουν",
              "Το χωριό του Πισιπούκ με δέντρα",
              "Ο Πισιπούκ στο λιμανάκι",
              "Οι φίλοι δημιουργούν στην τάξη",
            ][page % 4]
          }
        />
        <div>
          <small>ΣΕΛΙΔΑ {page + 1} / 5</small>
          <h3>{b.title}</h3>
          <p>{text}</p>
          {page === 4 && (
            <div className="pw-answers">
              {b.choices.map((c, i) => (
                <button
                  key={c}
                  aria-pressed={choice === i}
                  onClick={() => {
                    setChoice(i);
                    onComplete();
                  }}
                >
                  {c}
                </button>
              ))}
            </div>
          )}
          <div className="pw-tools">
            <button onClick={() => speak(text, setStatus)}>
              <Volume2 />
              Ελληνική αφήγηση
            </button>
            <button
              onClick={() => speechSynthesis.cancel()}
              aria-label="Διακοπή αφήγησης"
            >
              <Square />
            </button>
            <button
              aria-label="Προηγούμενη σελίδα"
              disabled={page === 0}
              onClick={() => {
                speechSynthesis.cancel();
                setPage(page - 1);
              }}
            >
              <ArrowLeft />
            </button>
            <button
              aria-label="Επόμενη σελίδα"
              disabled={page === 4}
              onClick={() => {
                speechSynthesis.cancel();
                setPage(page + 1);
              }}
            >
              <ArrowRight />
            </button>
          </div>
          <p className="pw-adult-prompt">Με τον ενήλικο: {agePrompt}</p>
        </div>
      </article>
      <div className="pw-replay-actions"><button type="button" onClick={()=>{window.speechSynthesis?.cancel();setBook(nextDifferent(STORIES.map((_,i)=>i),book));setPage(0);setChoice(null);}}>↻ Παίζω ξανά · Νέα ιστορία</button><button type="button" onClick={()=>{window.speechSynthesis?.cancel();setPage(0);setChoice(null);}}>↶ Ξανά η ίδια ιστορία</button></div>
      <button
        disabled={busy}
        onClick={async () => {
          setBusy(true);
          try {
            download(
              await makePdf(b.title, [...b.pages, ...b.endings, agePrompt]),
              "pisipouk-istoria-A4.pdf",
            );
            setStatus("Η ιστορία αποθηκεύτηκε ως PDF.");
          } catch {
            setStatus("Δεν δημιουργήθηκε το PDF. Δοκίμασε ξανά.");
          } finally {
            setBusy(false);
          }
        }}
      >
        {busy ? "Ετοιμάζεται…" : "Η ιστορία σε A4 PDF"}
      </button>
      <p role="status">{status}</p>
    </section>
  );
}
