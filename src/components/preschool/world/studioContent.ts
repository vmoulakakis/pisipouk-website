export function artwork(pattern:Pattern,age:number,colored=false):string {
  const width=age===0?11:age===1?9:age===2?7:6;
  const css=`<style>svg{background:#fff}.a,.b,.c,.d{stroke:#27353b;stroke-width:${width};stroke-linecap:round;stroke-linejoin:round}.a{fill:${colored?"#ffd767":"#fff"}}.b{fill:${colored?"#94dce5":"#fff"}}.c{fill:${colored?"#ff9f95":"#fff"}}.d{fill:${colored?"#4c4340":"#fff"}}path:not([class]),circle:not([class]),rect:not([class]),ellipse:not([class]){fill:none;stroke:#27353b;stroke-width:${width};stroke-linecap:round;stroke-linejoin:round}.details{display:${age<=1?"none":"initial"};fill:${colored?"#f5ab69":"none"};stroke:#27353b;stroke-width:5;stroke-linecap:round}</style>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="600" height="600" viewBox="0 0 600 600" role="img" aria-label="${pattern.title}">${css}${pattern.svg}</svg>`;
}
export function artworkDataUrl(pattern:Pattern,age:number,colored=false):string {
 return "data:image/svg+xml;charset=utf-8,"+encodeURIComponent(artwork(pattern,age,colored));
}
